// ===== Переключатель языков =====
var els = document.querySelectorAll('[data-i]');
var up = document.getElementById('up');
T.ru = { title: document.title, up: up.getAttribute('aria-label') };
els.forEach(function (el) { T.ru[el.dataset.i] = el.innerHTML; });

function setLang(l) {
  var d = T[l] || T.ru;
  els.forEach(function (el) { el.innerHTML = d[el.dataset.i]; });
  document.title = d.title;
  up.setAttribute('aria-label', d.up);
  document.documentElement.lang = l;
  document.querySelectorAll('#lang button').forEach(function (b) {
    b.classList.toggle('on', b.dataset.lang === l);
  });
  try { localStorage.setItem('lang', l); } catch (e) {}
}
document.getElementById('lang').addEventListener('click', function (e) {
  var b = e.target.closest('button');
  if (b) setLang(b.dataset.lang);
});
var saved = 'ru';
try { saved = localStorage.getItem('lang') || 'ru'; } catch (e) {}
setLang(saved);

// ===== Стрелка «наверх» =====
window.addEventListener('scroll', function () { up.classList.toggle('show', window.scrollY > 400); });
